#!/usr/bin/env python3
"""Generate oreoOS/tls_roots.py, the root CAs the badge trusts (#110).

Every HTTPS request on the badge goes through oreoOS._http.tls_wrap(),
which verifies the server's certificate chain against these roots. The
module holds each root as DER bytes; the badge imports it only when it
makes its first TLS connection.

    python3 tools/gen_ca_bundle.py                 # rewrite oreoOS/tls_roots.py
    python3 tools/gen_ca_bundle.py --check         # exit 1 if it is stale
    python3 tools/gen_ca_bundle.py --check-hosts   # verify every HOST below
                                                   # against the bundle only
                                                   # (needs the internet)

Roots are read from the computer's CA store (--certs-dir, default
/etc/ssl/certs, Mozilla's list as packaged by Debian/Ubuntu
ca-certificates). Root certificates are public; nothing here is secret.

Choosing roots: for each host the badge talks to, the root its chain ends
at today, plus a backup from the same CA family (so a CA re-issuing under
its other root does not break updates), plus GitHub's previous CA
(DigiCert) in case GitHub moves back. Run --check-hosts after any change,
and before a release, to catch a host that moved to a CA not listed here.
"""

import argparse
import hashlib
import socket
import ssl
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "oreoOS" / "tls_roots.py"

# Every TLS host the badge (OS, built-in apps, App Store apps) talks to.
# Keep in step with the code: tests/test_tls_verify.py greps for https://
# hosts and fails on one missing here.
HOSTS = (
    "api.github.com",                        # OTA tags, Contents API, profile
    "github.com",                            # release downloads, contributions
    "raw.githubusercontent.com",             # App Store catalogue and apps
    "release-assets.githubusercontent.com",  # release asset CDN (302 target)
    "objects.githubusercontent.com",         # older release asset CDN
    "codeload.github.com",                   # archive downloads (redirects)
    "ipwho.is",                              # oreoOS.geo
    "ipapi.co",                              # oreoOS.geo fallback
    "api.openweathermap.org",                # Weather app
    "speed.cloudflare.com",                  # Wi-Fi speed test
)

# (file stem in --certs-dir, why it is in the bundle)
ROOTS = (
    ("USERTrust_ECC_Certification_Authority",
     "GitHub (api.github.com, github.com, codeload): Sectigo E46 chain"),
    ("Sectigo_Public_Server_Authentication_Root_E46",
     "GitHub: the same chain ends here when the cross-sign is not sent"),
    ("USERTrust_RSA_Certification_Authority",
     "api.openweathermap.org (Sectigo R46 chain); Sectigo RSA backup"),
    ("Sectigo_Public_Server_Authentication_Root_R46",
     "api.openweathermap.org without the cross-sign; Sectigo RSA backup"),
    ("ISRG_Root_X1",
     "raw/release-assets/objects.githubusercontent.com (Let's Encrypt)"),
    ("ISRG_Root_X2",
     "Let's Encrypt ECDSA chains (backup)"),
    ("GTS_Root_R4",
     "ipwho.is, ipapi.co, speed.cloudflare.com (Google Trust Services)"),
    ("GTS_Root_R1",
     "Google Trust Services RSA chains (backup)"),
    ("DigiCert_Global_Root_G2",
     "GitHub's previous CA, RSA (backup)"),
    ("DigiCert_Global_Root_G3",
     "GitHub's previous CA, ECDSA (backup)"),
)


def _colon_hex(digest):
    h = digest.hex().upper()
    return ":".join(h[i:i + 2] for i in range(0, len(h), 2))


def _name(rdns):
    """'CN=..., O=..., C=...' from ssl's decoded subject."""
    parts = []
    short = {"commonName": "CN", "organizationName": "O",
             "organizationalUnitName": "OU", "countryName": "C"}
    for rdn in rdns:
        for key, value in rdn:
            if key in short:
                parts.append("%s=%s" % (short[key], value))
    return ", ".join(parts)


def load_roots(certs_dir):
    """[(stem, why, der, subject, not_after)] from the computer's store."""
    out = []
    for stem, why in ROOTS:
        path = Path(certs_dir) / (stem + ".pem")
        pem = path.read_text()
        der = ssl.PEM_cert_to_DER_cert(pem)
        info = ssl._ssl._test_decode_cert(str(path))
        out.append((stem, why, der, _name(info["subject"]),
                    info["notAfter"]))
    return out


def _bytes_lines(der, indent, width=60):
    lines = []
    for i in range(0, len(der), width):
        lines.append(indent + repr(der[i:i + width]))
    return lines


def render(roots):
    total = sum(len(r[2]) for r in roots)
    lines = [
        '"""Root CA certificates for HTTPS on the badge (#110).',
        "",
        "GENERATED by tools/gen_ca_bundle.py from Mozilla's CA list; do not",
        "edit by hand. oreoOS._http imports this module the first time it",
        "opens a TLS connection and loads every root into the SSLContext",
        "with load_verify_locations(cadata=<one DER certificate>).",
        "",
        "%d roots, %d bytes of DER. Each entry below records the root's"
        % (len(roots), total),
        "subject, SHA-256 fingerprint of the DER, expiry and why it is here;",
        "docs/TLS.md has the same table.",
        '"""',
        "",
        "ROOTS = (",
    ]
    for i, (stem, why, der, subject, not_after) in enumerate(roots, 1):
        fp = _colon_hex(hashlib.sha256(der).digest())
        lines += [
            "    # %d. %s" % (i, subject),
            "    #    sha256: %s" % fp,
            "    #    expires: %s" % not_after,
            "    #    for: %s" % why,
            "    (",
        ]
        lines += _bytes_lines(der, "        ")
        lines.append("    ),")
    lines.append(")")
    return "\n".join(lines) + "\n"


def docs_table(roots):
    """Markdown rows for docs/TLS.md."""
    rows = ["| # | Subject | SHA-256 | Expires | Why |",
            "|---|---|---|---|---|"]
    for i, (stem, why, der, subject, not_after) in enumerate(roots, 1):
        fp = hashlib.sha256(der).hexdigest().upper()
        rows.append("| %d | %s | `%s` | %s | %s |"
                    % (i, subject, fp, not_after, why))
    return "\n".join(rows)


def check_hosts(roots, timeout=10):
    """Handshake with every HOST trusting only the bundle. Returns the
    number of failures."""
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.verify_mode = ssl.CERT_REQUIRED
    ctx.check_hostname = True
    # Like the badge: each root on its own, nothing from the system store.
    for r in roots:
        ctx.load_verify_locations(cadata=r[2])
    bad = 0
    for host in HOSTS:
        try:
            with socket.create_connection((host, 443), timeout=timeout) as s:
                with ctx.wrap_socket(s, server_hostname=host) as t:
                    issuer = dict(x[0] for x in t.getpeercert()["issuer"])
                    print("ok    %-38s issuer %s"
                          % (host, issuer.get("commonName", "?")))
        except Exception as e:
            bad += 1
            print("FAIL  %-38s %s" % (host, e))
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--certs-dir", default="/etc/ssl/certs")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if oreoOS/tls_roots.py is out of date")
    ap.add_argument("--check-hosts", action="store_true",
                    help="verify every host against the bundle only")
    ap.add_argument("--docs", action="store_true",
                    help="print the Markdown table for docs/TLS.md")
    args = ap.parse_args(argv)

    roots = load_roots(args.certs_dir)
    if args.docs:
        print(docs_table(roots))
        return 0
    if args.check_hosts:
        return 1 if check_hosts(roots) else 0
    text = render(roots)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("oreoOS/tls_roots.py is stale: run tools/gen_ca_bundle.py")
            return 1
        print("oreoOS/tls_roots.py is up to date")
        return 0
    OUT.write_text(text)
    print("wrote %s: %d roots, %d bytes DER"
          % (OUT.relative_to(REPO), len(roots), sum(len(r[2]) for r in roots)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
