"""The badge owner's profile: who they are and where they are.

Badge, Identity, Commits, Weather and the clock read the owner's details
through this module instead of importing secrets.py directly, so a badge
can be set up without a repo checkout.

Lookup order for every key, first non-empty value wins:

  1. /profile.json on the badge. Writable at runtime; this is what a
     USB setup flow (`oreo setup`, planned) or an on-device editor saves.
  2. secrets.py, generated by tools/deploy.py from config.py + .env.local.
  3. The default the caller passes.

Keys use the secrets.py names so both sources line up:

  GITHUB_USER       GitHub login for Badge and Commits
  DISPLAY_NAME      name on the Identity card
  DISPLAY_DESIGNATION  one-line title under the name (DESIGNATION is
                    accepted as the older name)
  TIMEZONE_OFFSET   hours from UTC, e.g. 5.5 or -4
  WEATHER_LAT       latitude for Weather (float); optional: without it
  WEATHER_LON       Weather uses the badge's own location (oreoOS.geo)
  WEATHER_NAME      optional place name shown by Weather
  OWM_API_KEY       OpenWeatherMap API key

/profile.json is a flat JSON object with those keys. Unknown keys are
kept but ignored. Nothing in this module touches the network.
"""

from oreoOS import state as _state


PATH = "/profile.json"

KEYS = ("GITHUB_USER", "DISPLAY_NAME", "DISPLAY_DESIGNATION", "TIMEZONE_OFFSET",
        "WEATHER_LAT", "WEATHER_LON", "WEATHER_NAME", "OWM_API_KEY")
_NUMERIC = ("TIMEZONE_OFFSET", "WEATHER_LAT", "WEATHER_LON")
# The same value under its current and older name: .env.local and the CLI
# use DISPLAY_DESIGNATION, older secrets.py files and apps say DESIGNATION.
ALIASES = {"DESIGNATION": "DISPLAY_DESIGNATION",
           "DISPLAY_DESIGNATION": "DESIGNATION"}

_cache = None


def _read():
    global _cache
    if _cache is None:
        _cache = _state.read_json(PATH) or {}
    return _cache


def reload():
    """Forget the cached /profile.json, e.g. after a USB tool rewrote it."""
    global _cache
    _cache = None


def _from_secrets(key):
    try:
        import secrets
        return getattr(secrets, key, None)
    except Exception:
        return None


def _empty(v):
    return v is None or (isinstance(v, str) and not v.strip())


def get(key, default=None):
    """The owner's value for `key`, or `default` when nobody set it.
    /profile.json wins over secrets.py, under either name of an aliased key."""
    names = (key, ALIASES[key]) if key in ALIASES else (key,)
    v = None
    for n in names:
        v = _read().get(n)
        if not _empty(v):
            break
    if _empty(v):
        for n in names:
            v = _from_secrets(n)
            if not _empty(v):
                break
    if _empty(v):
        return default
    if key in _NUMERIC:
        try:
            return float(v)
        except (TypeError, ValueError):
            return default
    return v


def values():
    """Every known key with its resolved value (None when unset)."""
    return {k: get(k) for k in KEYS}


def is_set_up():
    """True when the owner has at least told the badge their GitHub user."""
    return not _empty(get("GITHUB_USER"))


def save(updates):
    """Merge `updates` into /profile.json atomically and return the result.

    Values of None or "" remove the key, so the secrets.py value (if any)
    shows through again. Raises ValueError for an unknown key or a
    non-numeric value for a numeric key, OSError if the write failed.
    """
    data = dict(_read())
    for k, v in updates.items():
        if k not in KEYS and ALIASES.get(k) in KEYS:
            data.pop(k, None)          # store under the current name only
            k = ALIASES[k]
        elif k in KEYS and k in ALIASES.values():
            for old, new in ALIASES.items():
                if new == k and old not in KEYS:
                    data.pop(old, None)
        if k not in KEYS:
            raise ValueError("unknown profile key: %s" % k)
        if _empty(v):
            data.pop(k, None)
            continue
        if k in _NUMERIC:
            v = float(v)
        data[k] = v
    if not _state.write_json(PATH, data):
        raise OSError("could not write " + PATH)
    reload()
    return data
