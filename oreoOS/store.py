# ── tiny HTTPS GET (whole body in RAM; catalogue and icons only) ────────

def _http_get(url, timeout_s=T_API, accept="*/*"):
    """GET url and return the body bytes on HTTP 200, else None."""
    if not _RAW_OK:
        return None
    try:
        from oreoOS import _http
        return _http.get_url(url, accept=accept, timeout_s=timeout_s)
    except Exception as e:
        _bc("get fail: " + str(e))
        return None


def _q(path):
    """URL-quote the one character our repo paths use (space)."""
    return path.replace(" ", "%20")


def raw_url(path):
    return "https://raw.githubusercontent.com/%s/%s/%s" % (
        STORE_REPO, STORE_REF, _q(path))


# ── filesystem helpers ──────────────────────────────────────────────────

def _exists(path):
    try:
        _os.stat(path)
        return True
    except OSError:
        return False


def _isdir(path):
    try:
        return (_os.stat(path)[0] & 0x4000) != 0
    except OSError:
        return False


def _ensure_dir(path):
    cur = "/" if path.startswith("/") else ""
    for p in path.split("/"):
        if not p:
            continue
        cur = cur + p if cur in ("", "/") else cur + "/" + p
        try:
            _os.mkdir(cur)
        except OSError:
            pass


def _rm_tree(path):
    try:
        names = _os.listdir(path)
    except OSError:
        try:
            _os.remove(path)
        except OSError:
            pass
        return
    for f in names:
        child = path + "/" + f
        if _isdir(child):
            _rm_tree(child)
        else:
            try:
                _os.remove(child)
            except OSError:
                pass
    try:
        _os.rmdir(path)
    except OSError:
        pass


def _tree_size(root):
    total = 0
    stack = [root]
    while stack:
        d = stack.pop()
        try:
            names = _os.listdir(d)
        except OSError:
            continue
        for f in names:
            p = d + "/" + f
            try:
                st = _os.stat(p)
            except OSError:
                continue
            if st[0] & 0x4000:
                stack.append(p)
            else:
                total += st[6]
    return total


def _read_json(path):
    if _json is None:
        return None
    try:
        with open(path) as f:
            return _json.loads(f.read())
    except Exception:
        return None


# ── catalogue validation ────────────────────────────────────────────────

_ID_FIRST = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_"
_ID_CHARS = _ID_FIRST + "0123456789"


def valid_id(value):
    """An importable package name: the on-badge app directory.

    ASCII only, checked against explicit character sets: MicroPython's str
    has no isalnum(), and its isalpha() accepts nothing beyond ASCII."""
    if not isinstance(value, str) or not value or len(value) > 32:
        return False
    if value[0] not in _ID_FIRST:
        return False
    for ch in value:
        if ch not in _ID_CHARS:
            return False
    return True


def safe_rel(rel):
    """A relative file path that stays inside the app directory."""
    if not isinstance(rel, str) or not rel or len(rel) > 96:
        return False
    if rel[0] == "/" or "\\" in rel:
        return False
    for part in rel.split("/"):
        if part in ("", ".", ".."):
            return False
    return True


def device_file(rel):
    """The files of an app that belong on the badge (same rule as
    tools/deploy.py): no raw/transparent PNGs, no host-only tests."""
    if rel in ("__init__.py", "main.py", "manifest.json",
               "assets/__init__.py"):
        return True
    parts = rel.split("/")
    if "__pycache__" in parts or "tests" in parts:
        return False
    if parts[0] == "src" and (rel.endswith(".py") or rel.endswith(".mpy")):
        return True
    if rel.startswith("assets/optimized/") and len(parts) == 3:
        return rel.endswith(".py")
    return False


def _text(v, fallback=""):
    return v if isinstance(v, str) else fallback


def _int(v):
    try:
        n = int(v)
        return n if n >= 0 else 0
    except Exception:
        return 0


def normalise_entry(raw):
    """Return a clean catalogue entry, or None if it is unusable."""
    if not isinstance(raw, dict):
        return None
    app_id = raw.get("id")
    path = raw.get("path")
    if not valid_id(app_id) or not isinstance(path, str) \
       or not path.startswith(MARKET_PATH + "/") or ".." in path:
        return None
    files = []
    fl = raw.get("files")
    if isinstance(fl, list):
        for item in fl:
            if isinstance(item, list) and len(item) == 2 \
               and safe_rel(item[0]) and device_file(item[0]):
                files.append((item[0], _int(item[1])))
    name = _text(raw.get("name"), app_id) or app_id
    desc = _text(raw.get("description"))
    entry = {
        "id":          app_id,
        "path":        path,
        "name":        name,
        "tagline":     _text(raw.get("tagline")) or desc,
        "description": desc,
        "category":    _text(raw.get("category"), "Apps") or "Apps",
        "author":      _text(raw.get("author")),
        "version":     _text(raw.get("version"), "0") or "0",
        "icon":        _text(raw.get("icon")),
        "size":        _int(raw.get("size")),
        "files":       files,
    }
    return entry


def parse_index(blob):
    """Parse index JSON (bytes/str/dict) → (apps, featured ids) or None."""
    if isinstance(blob, (bytes, bytearray)):
        try:
            blob = blob.decode()
        except Exception:
            return None
    if isinstance(blob, str):
        if _json is None:
            return None
        try:
            blob = _json.loads(blob)
        except Exception:
            return None
    if not isinstance(blob, dict) or not isinstance(blob.get("apps"), list):
        return None
    apps = []
    seen = set()
    for raw in blob["apps"]:
        e = normalise_entry(raw)
        if e and e["id"] not in seen:
            seen.add(e["id"])
            apps.append(e)
    featured = [f for f in (blob.get("featured") or [])
                if isinstance(f, str) and f in seen]
    return apps, featured


# ── versions and install state ──────────────────────────────────────────

def version_tuple(v):
    out = []
    for part in _text(v, "0").split("."):
        n = ""
        for ch in part:
            if ch.isdigit():
                n += ch
            else:
                break
        out.append(int(n) if n else 0)
    while len(out) > 1 and out[-1] == 0:
        out.pop()
    return tuple(out)


def is_newer(remote, local):
    return version_tuple(remote) > version_tuple(local)


_manifest_cache = {}   # id → manifest dict or False; cleared on changes


def installed_manifest(app_id):
    if app_id in _manifest_cache:
        return _manifest_cache[app_id] or None
    m = None
    root = APPS_DIR + "/" + app_id
    if _exists(root + "/main.py"):
        m = _read_json(root + "/manifest.json")
        if not isinstance(m, dict) or m.get("type", "app") != "app":
            m = None
    _manifest_cache[app_id] = m or False
    return m


def is_installed(app_id):
    return installed_manifest(app_id) is not None


def installed_version(app_id):
    m = installed_manifest(app_id)
    return _text(m.get("version"), "0") if m else None


def installed_size(app_id):
    return _tree_size(APPS_DIR + "/" + app_id)


def is_default(app_id):
    return app_id in DEFAULT_APPS


def app_state(entry):
    """INSTALL / OPEN / UPDATE for a catalogue entry."""
    v = installed_version(entry["id"])
    if v is None:
        return INSTALL
    if is_newer(entry["version"], v):
        return UPDATE
    return OPEN


def total_size(entry):
    return entry["size"]


def forget_installed():
    """Drop cached install state (after install/uninstall/deploy)."""
    _manifest_cache.clear()


# ── catalogue lifecycle ─────────────────────────────────────────────────

_apps = None          # list of entries
_featured = []
_refreshed_ms = None  # ticks_ms of the last successful refresh this boot
_last_error = ""


def catalogue():
    """(apps, featured) from memory, else the flash cache. Never blocks
    on the network."""
    global _apps, _featured
    if _apps is None:
        parsed = None
        try:
            with open(CACHE_PATH, "rb") as f:
                parsed = parse_index(f.read())
        except Exception:
            parsed = None
        if parsed:
            _apps, _featured = parsed
        else:
            _apps, _featured = [], []
    return _apps, _featured


def find(app_id):
    for e in catalogue()[0]:
        if e["id"] == app_id:
            return e
    return None


def wifi_up():
    try:
        from oreoWare import wifi
        return bool(wifi.is_connected())
    except Exception:
        return False


def needs_refresh(max_age_ms=15 * 60 * 1000):
    if _refreshed_ms is None:
        return True
    try:
        return time.ticks_diff(time.ticks_ms(), _refreshed_ms) > max_age_ms
    except Exception:
        return True


def refresh_due(max_age_ms=15 * 60 * 1000, net=None):
    """needs_refresh(), and also past netsvc's boot quiet window with no
    other background network thread running (netsvc.fetch_busy(): the
    clock sync or the OTA probe). The automatic refresh on opening the
    Store waits for both; a user's A press does not."""
    if not needs_refresh(max_age_ms):
        return False
    if net is None:
        try:
            from oreoOS import netsvc as net
        except Exception:
            return True
    try:
        if net.in_quiet():
            return False
    except Exception:
        return True
    try:
        return not net.fetch_busy()
    except Exception:
        return True


def fetch_index():
    """Network half of refresh(): GET and parse the catalogue. Touches no
    module state and no files, so it can run on a worker thread (the
    Store app runs it in an oreoOS.cache.Refresh job). Returns
    (body, parsed) or (None, error)."""
    if not wifi_up():
        return None, "offline"
    _bc("refresh " + STORE_REF)
    body = _http_get(raw_url(INDEX_PATH))
    parsed = parse_index(body) if body else None
    if not parsed:
        return None, "catalogue unavailable"
    return body, parsed


def apply_index(result):
    """UI-thread half of refresh(): adopt a fetch_index() result, write
    the flash cache and prune. Returns True on success; on failure the
    cached catalogue stays and last_error() says why."""
    global _apps, _featured, _refreshed_ms, _last_error
    catalogue()
    body, parsed = result if result else (None, "catalogue unavailable")
    if body is None:
        _last_error = parsed or "catalogue unavailable"
        return False
    _apps, _featured = parsed
    _last_error = ""
    try:
        _refreshed_ms = time.ticks_ms()
    except Exception:
        _refreshed_ms = 0
    try:
        with open(CACHE_PATH, "wb") as f:
            f.write(body)
    except Exception:
        pass
    del body
    _prune_icons()
    _migrate_legacy()
    # Caches written by the pre-2.0 Store.
    for old in ("/store_cache.json", "/store_details"):
        if _exists(old):
            _rm_tree(old)
    gc.collect()
    return True


def refresh():
    """Fetch the catalogue, blocking. Returns True on success; on failure
    the cached catalogue stays and last_error() says why. The Store app
    runs fetch_index() on a thread and apply_index() itself instead."""
    catalogue()
    return apply_index(fetch_index())


def last_error():
    return _last_error


def _migrate_legacy():
    """Older Stores installed market apps under their market folder name
    (e.g. "Oreo Pet"), which cannot be imported. Move them to the id."""
    for e in _apps or ():
        folder = e["path"][len(MARKET_PATH) + 1:]
        if folder == e["id"]:
            continue
        old = APPS_DIR + "/" + folder
        new = APPS_DIR + "/" + e["id"]
        if _exists(old) and not _exists(new):
            try:
                _os.rename(old, new)
                _manifest_cache.pop(e["id"], None)
            except OSError:
                pass


# ── icons ───────────────────────────────────────────────────────────────

def _icon_stem(icon):
    return icon.rsplit(".", 1)[0].replace("-", "_")


def _valid_icon_module(body):
    return b"DATA = (" in body and b"W =" in body and b"H =" in body


def local_icon(entry_id, icon):
    """(data, w, h) from icons shipped in the OS image, the installed app
    or the Store's icon cache, without touching the network."""
    if icon:
        try:
            from oreoOS import icons as _icons
            res = _icons.load(entry_id, icon)
            if res:
                return res
        except Exception:
            pass
    path = ICONS_DIR + "/" + entry_id + ".py"
    if _exists(path):
        try:
            ns = {}
            with open(path) as f:
                exec(f.read(), ns)
            return (bytearray(ns["DATA"]), int(ns["W"]), int(ns["H"]))
        except Exception:
            try:
                _os.remove(path)
            except OSError:
                pass
    if icon and is_installed(entry_id):
        try:
            m = __import__("apps.%s.assets.optimized.%s"
                           % (entry_id, _icon_stem(icon)),
                           None, None, ["DATA", "W", "H"])
            return (m.DATA, m.W, m.H)
        except Exception:
            pass
    return None


def icon_fetch_ok(net=None):
    """True when the Store may start an icon download now: past netsvc's
    boot quiet window and with no other background network thread
    (netsvc.fetch_busy(): the clock sync or the OTA probe), the same gate
    as the automatic catalogue refresh, so two TLS sessions never share
    the heap. Not netsvc.background_ok(): that is a 15-minute grace for
    work nobody asked for (the OTA probe); the user opened the Store."""
    if net is None:
        try:
            from oreoOS import netsvc as net
        except Exception:
            return True
    try:
        if net.in_quiet():
            return False
    except Exception:
        pass
    try:
        return not net.fetch_busy()
    except Exception:
        return True


def fetch_icon_body(entry):
    """Network half of fetch_icon(): the icon module's bytes, or None.
    Touches no files and no module state, so it can run on a worker
    thread (the Store runs it in an oreoOS.cache.Refresh job)."""
    icon = entry.get("icon")
    if not icon or not wifi_up():
        return None
    url = raw_url("%s/assets/optimized/%s.py" % (entry["path"],
                                                 _icon_stem(icon)))
    body = _http_get(url)
    if not body or not _valid_icon_module(body):
        return None
    return body


def save_icon(entry_id, body):
    """UI-thread half: write a fetch_icon_body() result into the icon
    cache. Returns True when a usable icon is now cached."""
    if not body or not valid_id(entry_id) or not _valid_icon_module(body):
        return False
    _ensure_dir(ICONS_DIR)
    try:
        with open(ICONS_DIR + "/" + entry_id + ".py", "wb") as f:
            f.write(body)
        return True
    except Exception:
        return False


def fetch_icon(entry):
    """Download an app's optimized icon module into the icon cache,
    blocking. Returns True when a usable icon is now cached."""
    return save_icon(entry["id"], fetch_icon_body(entry))


def _prune_icons():
    live = set(e["id"] + ".py" for e in _apps or ())
    try:
        for f in _os.listdir(ICONS_DIR):
            if f not in live:
                try:
                    _os.remove(ICONS_DIR + "/" + f)
                except OSError:
                    pass
    except OSError:
        pass


# ── installed apps ──────────────────────────────────────────────────────

def list_installed():
    """Installed apps as the launcher sees them, defaults first."""
    try:
        from oreoOS.launcher import list_apps
        apps = list_apps()
    except Exception:
        apps = []
    out = [a for a in apps if a.get("dir") not in HIDDEN_INSTALLED]
    out.sort(key=lambda a: (0 if is_default(a["dir"]) else 1,
                            str(a.get("name") or a["dir"]).lower()))
    return out


# ── install / uninstall ─────────────────────────────────────────────────

def _fallback_files(entry):
    """File list from the GitHub API when an index entry has none (a new
    app added before the index was regenerated)."""
    out = []
    stack = [entry["path"]]
    prefix = entry["path"] + "/"
    while stack and len(out) < 200:
        path = stack.pop()
        body = _http_get("https://api.github.com/repos/%s/contents/%s?ref=%s"
                         % (STORE_REPO, _q(path), STORE_REF),
                         accept="application/vnd.github+json")
        try:
            items = _json.loads(body.decode()) if body else None
        except Exception:
            items = None
        if not isinstance(items, list):
            return None
        for it in items:
            if not isinstance(it, dict):
                continue
            p = _text(it.get("path"))
            if not p.startswith(prefix):
                continue
            rel = p[len(prefix):]
            if it.get("type") == "dir":
                if rel.split("/")[0] in ("src", "assets"):
                    stack.append(p)
            elif it.get("type") == "file" and safe_rel(rel) \
                    and device_file(rel):
                out.append((rel, _int(it.get("size"))))
    return out


def _io():
    """The streaming download helpers, imported only when installing."""
    from oreoOS import store_io
    return store_io


def _report(cb, received, total, label):
    if cb is not None:
        try:
            cb(received, total, label)
        except Exception:
            pass


def install(app_id, progress_cb=None):
    """Install or update an app. progress_cb(received, total, label).
    Returns (ok, message)."""
    entry = find(app_id)
    if entry is None:
        return False, "not in catalogue"
    if is_default(app_id):
        return False, "built-in app"
    if not wifi_up():
        return False, "no WiFi"
    files = entry["files"] or _fallback_files(entry)
    if not files:
        return False, "no file list"
    names = [f[0] for f in files]
    if "main.py" not in names or "manifest.json" not in names:
        return False, "incomplete app"

    total = sum(f[1] for f in files)
    done = 0

    # 1. App files into a staging directory, manifest.json last.
    stage = TMP_DIR + "/" + app_id
    store_io = _io()
    _rm_tree(stage)
    _ensure_dir(stage)
    files = [f for f in files if f[0] != "manifest.json"] + \
            [f for f in files if f[0] == "manifest.json"]
    buf = bytearray(store_io.CHUNK)
    for rel, size in files:
        dst = stage + "/" + rel
        if "/" in rel:
            _ensure_dir(dst.rsplit("/", 1)[0])
        base = done

        def _fp(received, _t, base=base):
            _report(progress_cb, base + received, total, "Downloading")
        url = raw_url(entry["path"] + "/" + rel)
        if not store_io.download_file(url, dst, size if entry["files"] else -1,
                                      _fp, buf):
            _rm_tree(stage)
            return False, "download failed"
        done += size
        _report(progress_cb, done, total, "Downloading")
    m = _read_json(stage + "/manifest.json")
    if not isinstance(m, dict) or m.get("type", "app") != "app":
        _rm_tree(stage)
        return False, "bad manifest"

    # 2. Swap into place; the old version stays until the new one is whole.
    target = APPS_DIR + "/" + app_id
    old = TMP_DIR + "/" + app_id + ".old"
    _rm_tree(old)
    try:
        if _exists(target):
            _os.rename(target, old)
        _os.rename(stage, target)
    except OSError:
        if _exists(old) and not _exists(target):
            try:
                _os.rename(old, target)
            except OSError:
                pass
        _rm_tree(stage)
        return False, "could not write app"
    # Saves the app wrote into its own folder (high scores, pet state)
    # move across to the new version before the old copy is deleted.
    _carry_user_files(old, target)
    _rm_tree(old)
    forget_installed()
    _invalidate_launcher()
    gc.collect()
    return True, "installed"


def _carry_user_files(src, dst, rel=""):
    """Move files from an app's previous copy that are not part of the
    package (anything device_file() rejects) into the new copy."""
    try:
        names = _os.listdir(src + ("/" + rel if rel else ""))
    except OSError:
        return
    for name in names:
        r = rel + "/" + name if rel else name
        if name == "__pycache__":
            continue
        s, d = src + "/" + r, dst + "/" + r
        if _isdir(s):
            _carry_user_files(src, dst, r)
        elif not device_file(r) and not _exists(d):
            try:
                if "/" in r:
                    _ensure_dir(d.rsplit("/", 1)[0])
                _os.rename(s, d)
            except OSError:
                pass


def uninstall(app_id):
    """Remove an installed app. Built-in apps are refused."""
    if is_default(app_id) or not valid_id(app_id):
        return False, "built-in app"
    target = APPS_DIR + "/" + app_id
    if _exists(target):
        _rm_tree(target)
    forget_installed()
    _invalidate_launcher()
    if _exists(target):
        return False, "could not remove"
    return True, "removed"


# ── opening store apps from elsewhere ───────────────────────────────────

_pending = None


def open_app(os_, app_id):
    """Launch an app if it is installed, otherwise open the App Store on
    its page so the user can install it (Settings uses this for the
    Bluetooth and Gestures apps, which are no longer built in)."""
    global _pending
    if is_installed(app_id):
        os_.launch(app_id)
        return
    _pending = app_id
    os_.launch("store")


def take_pending():
    """The app id open_app() asked the Store to show, once."""
    global _pending
    app_id, _pending = _pending, None
    return app_id


def _invalidate_launcher():
    try:
        from apps.launcher.src.app import invalidate_apps_cache
        invalidate_apps_cache()
    except Exception:
        pass
