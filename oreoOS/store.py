"""App Store backend: catalogue, icons, install, update and uninstall.

Catalogue: one JSON file, apps_market/index.json in github.com/elixpo/oreo,
generated by tools/build_store_index.py. It carries everything the Store
shows (name, tagline, description, category, author, version, size, icon)
plus the exact list of device files per app, so browsing costs a single
raw.githubusercontent.com request and installing needs no GitHub API calls.
The last good copy lives on flash (/store_index.json) and is shown
immediately; refresh() replaces it when the network is up.

Installed apps are directories under /apps/<id>/ with main.py and a
manifest.json of type "app"; that is exactly what the launcher lists
(oreoOS.launcher.list_apps). Installs download into /store_tmp/<id>/ and
are moved into /apps only when every file arrived with the expected size,
so a failed install or update never leaves a broken app behind and an
update keeps the old version until the new one is complete.
"""

import gc
import os as _os
import time

try:
    import json as _json
except ImportError:
    _json = None
try:
    import socket as _socket
    import ssl as _ssl
    _RAW_OK = True
except ImportError:
    _RAW_OK = False


def _bc(msg):
    try:
        print("[store] " + msg)
    except Exception:
        pass


